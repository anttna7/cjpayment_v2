/**
 * 最终的添加商户模态框测试
 */

const puppeteer = require('puppeteer');

async function finalTest() {
    const browser = await puppeteer.launch({
        headless: false,
        defaultViewport: { width: 1280, height: 720 }
    });
    
    const page = await browser.newPage();
    
    // 监听控制台和错误
    page.on('console', msg => {
        const text = msg.text();
        if (!text.includes('HeaderUnified') && 
            !text.includes('NotificationDataUnified') &&
            !text.includes('User Feedback Analytics')) {
            console.log(`浏览器: ${text}`);
        }
    });
    page.on('pageerror', error => console.error(`页面错误: ${error.message}`));
    
    try {
        console.log('🚀 开始最终测试...\n');
        
        console.log('📡 导航到商户管理页面...');
        await page.goto('http://localhost:8092/merchant', { 
            waitUntil: 'networkidle0',
            timeout: 15000 
        });
        
        // 等待页面完全加载
        await new Promise(resolve => setTimeout(resolve, 3000));
        
        console.log('🔍 检查模态框组件状态...');
        const componentStatus = await page.evaluate(() => {
            return {
                addMerchant: typeof window.addMerchant,
                hasModal: !!document.getElementById('addMerchantModal'),
                modalInstance: typeof addMerchantModal,
                hasButton: !!document.getElementById('addMerchant'),
                hasCssClass: !!document.querySelector('.modal-overlay')
            };
        });
        
        console.log(`  ✅ addMerchant函数: ${componentStatus.addMerchant}`);
        console.log(`  ✅ 模态框DOM: ${componentStatus.hasModal}`);
        console.log(`  ✅ 模态框实例: ${componentStatus.modalInstance}`);
        console.log(`  ✅ 添加按钮: ${componentStatus.hasButton}`);
        console.log(`  ✅ CSS样式: ${componentStatus.hasCssClass}`);
        
        if (componentStatus.addMerchant === 'function' && componentStatus.hasModal && componentStatus.hasButton) {
            console.log('\n🎯 测试1：打开模态框...');
            await page.evaluate(() => window.addMerchant());
            await new Promise(resolve => setTimeout(resolve, 500));
            
            const modalOpen = await page.evaluate(() => {
                const modal = document.getElementById('addMerchantModal');
                return modal ? {
                    display: window.getComputedStyle(modal).display,
                    hasShowClass: modal.classList.contains('show'),
                    opacity: window.getComputedStyle(modal).opacity,
                    visibility: window.getComputedStyle(modal).visibility
                } : null;
            });
            
            if (modalOpen && modalOpen.hasShowClass && modalOpen.display === 'flex') {
                console.log('  ✅ 模态框成功打开');
                await page.screenshot({ path: 'final-test-01-modal-opened.png', fullPage: true });
                
                console.log('\n🎯 测试2：输入商户名称并检查自动生成...');
                await page.type('#merchantName', '测试科技有限公司');
                await new Promise(resolve => setTimeout(resolve, 1000));
                
                const autoGenerated = await page.evaluate(() => {
                    return {
                        merchantId: document.getElementById('merchantId')?.value || '',
                        rechargeUrl: document.getElementById('rechargeUrl')?.value || ''
                    };
                });
                
                if (autoGenerated.merchantId && autoGenerated.rechargeUrl) {
                    console.log('  ✅ 自动生成成功');
                    console.log(`     商户ID: ${autoGenerated.merchantId}`);
                    console.log(`     充值链接: ${autoGenerated.rechargeUrl}`);
                    
                    await page.screenshot({ path: 'final-test-02-auto-generated.png', fullPage: true });
                    
                    console.log('\n🎯 测试3：添加动态账户...');
                    
                    // 添加付款账户
                    await page.click('#addPaymentAccount');
                    await new Promise(resolve => setTimeout(resolve, 300));
                    
                    // 填写付款账户信息
                    await page.type('input[name="paymentAccountName_1"]', '测试银行账户');
                    await page.type('input[name="paymentAccountNumber_1"]', '6217001234567890');
                    
                    // 添加广告账户
                    await page.click('#addAdAccount');
                    await new Promise(resolve => setTimeout(resolve, 300));
                    
                    // 填写广告账户信息
                    await page.type('input[name="adAccountId_1"]', 'AD789456');
                    await page.type('input[name="adAccountName_1"]', '测试广告账户');
                    
                    console.log('  ✅ 动态账户添加成功');
                    await page.screenshot({ path: 'final-test-03-dynamic-accounts.png', fullPage: true });
                    
                    console.log('\n🎯 测试4：填写完整表单...');
                    await page.type('#contactName', '张三');
                    await page.type('#contactPhone', '13800138000');
                    await page.type('#contactEmail', 'test@example.com');
                    await page.type('#industry', '科技服务');
                    await page.type('#merchantDescription', '这是一个完整的测试商户，用于验证添加商户模态框的所有功能。');
                    
                    console.log('  ✅ 表单填写完成');
                    await page.screenshot({ path: 'final-test-04-complete-form.png', fullPage: true });
                    
                    console.log('\n🎯 测试5：测试复制功能...');
                    await page.click('#copyRechargeUrl');
                    await new Promise(resolve => setTimeout(resolve, 1000));
                    
                    const copyButtonText = await page.evaluate(() => {
                        const btn = document.getElementById('copyRechargeUrl');
                        return btn ? btn.textContent.trim() : '';
                    });
                    
                    if (copyButtonText.includes('已复制')) {
                        console.log('  ✅ 复制功能正常');
                    } else {
                        console.log('  ⚠️ 复制功能可能有问题');
                    }
                    
                    console.log('\n🎯 测试6：关闭模态框...');
                    await page.click('.modal-close');
                    await new Promise(resolve => setTimeout(resolve, 500));
                    
                    const modalClosed = await page.evaluate(() => {
                        const modal = document.getElementById('addMerchantModal');
                        return modal ? !modal.classList.contains('show') : true;
                    });
                    
                    if (modalClosed) {
                        console.log('  ✅ 模态框成功关闭');
                    } else {
                        console.log('  ❌ 模态框关闭失败');
                    }
                    
                    console.log('\n🎉 所有测试完成！功能正常');
                    
                } else {
                    console.log('  ❌ 自动生成功能失败');
                    console.log(`     商户ID: "${autoGenerated.merchantId}"`);
                    console.log(`     充值链接: "${autoGenerated.rechargeUrl}"`);
                }
                
            } else {
                console.log('  ❌ 模态框打开失败');
                console.log(`     Display: ${modalOpen?.display}`);
                console.log(`     Show class: ${modalOpen?.hasShowClass}`);
                console.log(`     Opacity: ${modalOpen?.opacity}`);
                console.log(`     Visibility: ${modalOpen?.visibility}`);
            }
        } else {
            console.log('❌ 组件检查失败，无法继续测试');
        }
        
    } catch (error) {
        console.error('❌ 测试过程中发生错误:', error);
        await page.screenshot({ path: 'final-test-error.png', fullPage: true });
    } finally {
        console.log('\n⏱️ 保持浏览器开启10秒以供检查...');
        await new Promise(resolve => setTimeout(resolve, 10000));
        await browser.close();
        console.log('🏁 测试结束');
    }
}

finalTest().catch(console.error);