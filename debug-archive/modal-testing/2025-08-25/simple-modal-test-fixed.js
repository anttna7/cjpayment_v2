/**
 * 修复后的简单模态框测试脚本
 */

const puppeteer = require('puppeteer');

async function testModalFixed() {
    const browser = await puppeteer.launch({
        headless: false,
        defaultViewport: { width: 1280, height: 720 }
    });
    
    const page = await browser.newPage();
    
    // 监听控制台和错误
    page.on('console', msg => {
        const text = msg.text();
        if (!text.includes('HeaderUnified') && !text.includes('NotificationDataUnified')) {
            console.log(`浏览器: ${text}`);
        }
    });
    page.on('pageerror', error => console.error(`页面错误: ${error.message}`));
    
    try {
        console.log('导航到商户管理页面...');
        await page.goto('http://localhost:8092/merchant', { 
            waitUntil: 'networkidle0',
            timeout: 15000 
        });
        
        // 等待页面完全加载
        await new Promise(resolve => setTimeout(resolve, 2000));
        
        console.log('检查addMerchant函数是否可用...');
        const functionCheck = await page.evaluate(() => {
            return {
                addMerchant: typeof window.addMerchant,
                hasModal: !!document.getElementById('addMerchantModal'),
                modalInstance: typeof addMerchantModal
            };
        });
        
        console.log(`  window.addMerchant: ${functionCheck.addMerchant}`);
        console.log(`  modal元素存在: ${functionCheck.hasModal}`);
        console.log(`  modal实例: ${functionCheck.modalInstance}`);
        
        if (functionCheck.addMerchant === 'function') {
            console.log('\n✅ 手动调用addMerchant函数...');
            await page.evaluate(() => {
                window.addMerchant();
            });
            
            await new Promise(resolve => setTimeout(resolve, 500));
            
            const modalState = await page.evaluate(() => {
                const modal = document.getElementById('addMerchantModal');
                return modal ? {
                    display: window.getComputedStyle(modal).display,
                    hasShowClass: modal.classList.contains('show'),
                    opacity: window.getComputedStyle(modal).opacity
                } : null;
            });
            
            if (modalState) {
                console.log(`模态框状态: display=${modalState.display}, show=${modalState.hasShowClass}, opacity=${modalState.opacity}`);
                
                if (modalState.hasShowClass) {
                    console.log('🎉 模态框成功打开！');
                    await page.screenshot({ path: 'modal-success.png', fullPage: true });
                    
                    // 测试输入功能
                    console.log('\n测试输入功能...');
                    await page.type('#merchantName', '测试商户公司');
                    await new Promise(resolve => setTimeout(resolve, 1000));
                    
                    // 检查自动生成
                    const autoGenerated = await page.evaluate(() => {
                        return {
                            merchantId: document.getElementById('merchantId')?.value || '',
                            rechargeLink: document.getElementById('rechargeLink')?.value || ''
                        };
                    });
                    
                    console.log(`自动生成的商户ID: ${autoGenerated.merchantId}`);
                    console.log(`自动生成的充值链接: ${autoGenerated.rechargeLink}`);
                    
                    await page.screenshot({ path: 'modal-with-data.png', fullPage: true });
                    
                } else {
                    console.log('❌ 模态框未正确显示');
                    await page.screenshot({ path: 'modal-not-shown.png', fullPage: true });
                }
            } else {
                console.log('❌ 模态框元素不存在');
            }
        } else {
            console.log('❌ addMerchant函数不可用');
        }
        
    } catch (error) {
        console.error('测试失败:', error);
        await page.screenshot({ path: 'test-error.png', fullPage: true });
    } finally {
        console.log('\n测试完成，等待5秒后关闭浏览器...');
        await new Promise(resolve => setTimeout(resolve, 5000));
        await browser.close();
    }
}

testModalFixed().catch(console.error);