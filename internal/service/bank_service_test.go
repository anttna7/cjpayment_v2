func TestBankService_ProcessBankCallback(t *testing.T) {
	mockRepo := new(MockRechargeOrderRepository)
	config := &BankConfig{
		SignatureKey: "test-signature-key",
	}
	service := NewBankService(mockRepo, config)
	ctx := context.Background()
	
	orderID := uuid.New()
	order := &repository.RechargeOrder{
		ID:     orderID,
		Amount: decimal.NewFromFloat(1000.00),
		Status: "pending",
	}
	
	// Create a valid callback (signature will be generated by the service)
	callback := &BankCallbackRequest{
		TransferID:    "BT20250101120000abcd1234",
		OrderID:       orderID.String(),
		Status:        BankTransferStatusSuccess,
		Amount:        decimal.NewFromFloat(1000.00),
		PayerName:     "Test Company",
		PayerAccount:  "1234567890",
		TransferTime:  time.Now(),
		BankReference: "REF123456",
		Timestamp:     time.Now().Unix(),
	}
	
	// Generate signature for the callback
	bankService := service.(*bankService)
	data := map[string]interface{}{
		"transfer_id":    callback.TransferID,
		"order_id":       callback.OrderID,
		"status":         callback.Status,
		"amount":         callback.Amount.String(),
		"payer_name":     callback.PayerName,
		"payer_account":  callback.PayerAccount,
		"bank_reference": callback.BankReference,
		"timestamp":      callback.Timestamp,
	}
	signature, _ := bankService.generateSignature(data)
	callback.Signature = signature

	mockRepo.On("GetByID", ctx, orderID).Return(order, nil)
	mockRepo.On("Update", ctx, mock.AnythingOfType("*repository.RechargeOrder")).Return(nil)

	// Execute
	response, err := service.ProcessBankCallback(ctx, callback)

	// Assertions
	assert.NoError(t, err)
	assert.NotNil(t, response)
	assert.True(t, response.Success)
	assert.Equal(t, "SUCCESS", response.Code)
	
	mockRepo.AssertExpectations(t)
}

