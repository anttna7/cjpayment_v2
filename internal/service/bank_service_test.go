func TestBankService_ValidateBankCallback(t *testing.T) {
	service := NewBankService(nil, &BankConfig{})
	ctx := context.Background()
	
	tests := []struct {
		name        string
		callback    *BankCallbackRequest
		expectError bool
	}{
		{
			name: "Valid callback",
			callback: &BankCallbackRequest{
				Status:    BankTransferStatusSuccess,
				Amount:    decimal.NewFromFloat(1000.00),
				Timestamp: time.Now().Unix(),
			},
			expectError: false,
		},
		{
			name: "Invalid status",
			callback: &BankCallbackRequest{
				Status:    "invalid_status",
				Amount:    decimal.NewFromFloat(1000.00),
				Timestamp: time.Now().Unix(),
			},
			expectError: true,
		},
		{
			name: "Invalid amount",
			callback: &BankCallbackRequest{
				Status:    BankTransferStatusSuccess,
				Amount:    decimal.NewFromFloat(-100.00),
				Timestamp: time.Now().Unix(),
			},
			expectError: true,
		},
		{
			name: "Old timestamp",
			callback: &BankCallbackRequest{
				Status:    BankTransferStatusSuccess,
				Amount:    decimal.NewFromFloat(1000.00),
				Timestamp: time.Now().Unix() - 600, // 10 minutes ago
			},
			expectError: true,
		},
	}
	
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			err := service.ValidateBankCallback(ctx, tt.callback)
			if tt.expectError {
				assert.Error(t, err)
			} else {
				assert.NoError(t, err)
			}
		})
	}
}

func TestBankService_GenerateSignature(t *testing.T) {
	config := &BankConfig{
		SignatureKey: "test-signature-key",
	}
	service := NewBankService(nil, config).(*bankService)
	
	data := map[string]interface{}{
		"transfer_id": "BT20250101120000abcd1234",
		"order_id":    "12345678-1234-1234-1234-123456789012",
		"status":      "success",
		"amount":      "1000.00",
	}
	
	// Generate signature
	signature1, err1 := service.generateSignature(data)
	signature2, err2 := service.generateSignature(data)
	
	// Assertions
	assert.NoError(t, err1)
	assert.NoError(t, err2)
	assert.NotEmpty(t, signature1)
	assert.Equal(t, signature1, signature2) // Same data should produce same signature
	
	// Different data should produce different signature
	data["amount"] = "2000.00"
	signature3, err3 := service.generateSignature(data)
	assert.NoError(t, err3)
	assert.NotEqual(t, signature1, signature3)
}