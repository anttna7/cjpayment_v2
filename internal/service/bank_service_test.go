func TestBankService_InitiateBankTransfer(t *testing.T) {
	mockRepo := new(MockRechargeOrderRepository)
	config := &BankConfig{
		APIBaseURL:    "https://api.bank.example.com",
		APIKey:        "test-key",
		APISecret:     "test-secret",
		SignatureKey:  "test-signature-key",
		Timeout:       30 * time.Second,
		RetryAttempts: 3,
	}
	
	service := NewBankService(mockRepo, config)
	ctx := context.Background()
	
	// Test data
	orderID := uuid.New()
	order := &repository.RechargeOrder{
		ID:          orderID,
		OrderNumber: "CJ202501011234567890",
		PaymentType: "public",
		Status:      "pending",
		Amount:      decimal.NewFromFloat(1000.00),
		CreatedAt:   time.Now(),
		UpdatedAt:   time.Now(),
	}
	
	req := &InitiateBankTransferRequest{
		OrderID:         orderID,
		PayerName:       "Test Company",
		PayerAccount:    "1234567890",
		Amount:          decimal.NewFromFloat(1000.00),
		ReceiverName:    "Receive Company",
		ReceiverAccount: "0987654321",
		BankName:        "Test Bank",
		BankBranch:      nil,
		Purpose:         "Test transfer",
		NotifyURL:       "https://example.com/callback",
		ReturnURL:       "https://example.com/return",
	}

	// Mock expectations
	mockRepo.On("GetByID", ctx, orderID).Return(order, nil)
	mockRepo.On("Update", ctx, mock.AnythingOfType("*repository.RechargeOrder")).Return(nil)

	// Execute
	response, err := service.InitiateBankTransfer(ctx, req)

	// Assertions
	assert.NoError(t, err)
	assert.NotNil(t, response)
	assert.Equal(t, orderID, response.OrderID)
	assert.Equal(t, BankTransferStatusPending, response.Status)
	assert.NotEmpty(t, response.TransferID)
	assert.NotEmpty(t, response.TransferURL)
	assert.NotEmpty(t, response.BankReference)
	
	mockRepo.AssertExpectations(t)
}

